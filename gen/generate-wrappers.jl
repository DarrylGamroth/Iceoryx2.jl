const _HANDLE_RE = r"^const iox2_([a-z0-9_]+)_h\s*="m
const _HANDLE_REF_RE = r"^const iox2_([a-z0-9_]+)_h_ref\s*="m
const _PTR_RE = r"^const iox2_([a-z0-9_]+)_ptr\s*="m
const _DROP_RE = r"^function iox2_([a-z0-9_]+)_drop\b"m
const _ENUM_RE = r"^@cenum\s+iox2_([a-z0-9_]+)_(error|failure)_e\b"m
const _ERRSTR_RE = r"^function iox2_([a-z0-9_]+)_(error|failure)_(string|create_error_string)\b"m

function _camelcase(name::AbstractString)
    parts = split(name, '_')
    return join(uppercasefirst.(parts))
end

function _collect_basenames(regex::Regex, text::AbstractString)
    return Set(String(m.captures[1]) for m in eachmatch(regex, text))
end

function _collect_error_strings(text::AbstractString)
    mapping = Dict{Tuple{String,String},String}()
    for m in eachmatch(_ERRSTR_RE, text)
        base = String(m.captures[1])
        kind = String(m.captures[2])
        suffix = String(m.captures[3])
        func = "iox2_$(base)_$(kind)_$(suffix)"
        mapping[(base, kind)] = func
    end
    return mapping
end

function generate_handles(ffi_text::AbstractString, out_path::AbstractString; ignore_owning::Set{String}=Set{String}())
    handles = _collect_basenames(_HANDLE_RE, ffi_text)
    drops = _collect_basenames(_DROP_RE, ffi_text)
    refs = _collect_basenames(_HANDLE_REF_RE, ffi_text)
    ptrs = _collect_basenames(_PTR_RE, ffi_text)

    owning = sort([h for h in handles if h in drops && !(h in ignore_owning)])
    ref_list = sort(collect(refs))
    ptr_list = sort(collect(ptrs))

    io = IOBuffer()
    println(io, "# This file is autogenerated by gen/gen-bindings.jl from src/Iceoryx2FFI.jl. Do not edit by hand.")
    println(io)
    println(io, "const _IOX2_NULL = C_NULL")
    println(io)

    for base in owning
        tname = _camelcase(base)
        dropfn = "iox2_$(base)_drop"
        println(io, "mutable struct $tname")
        println(io, "    handle::Iceoryx2FFI.iox2_$(base)_h")
        println(io, "    function $tname(handle::Iceoryx2FFI.iox2_$(base)_h)")
        println(io, "        obj = new(handle)")
        println(io, "        finalizer(_finalize_$tname, obj)")
        println(io, "        return obj")
        println(io, "    end")
        println(io, "end")
        println(io)
        println(io, "@inline unsafe_handle(obj::$tname) = obj.handle")
        println(io, "@inline Base.isvalid(obj::$tname) = obj.handle != _IOX2_NULL")
        println(io, "@inline invalidate!(obj::$tname) = (obj.handle = _IOX2_NULL)")
        println(io)
        println(io, "function _finalize_$tname(obj::$tname)")
        println(io, "    if obj.handle != _IOX2_NULL")
        println(io, "        Iceoryx2FFI.$dropfn(obj.handle)")
        println(io, "        obj.handle = _IOX2_NULL")
        println(io, "    end")
        println(io, "    return nothing")
        println(io, "end")
        println(io)
        println(io, "function Base.close(obj::$tname)")
        println(io, "    _finalize_$tname(obj)")
        println(io, "    return nothing")
        println(io, "end")
        println(io)
    end

    for base in ref_list
        tname = _camelcase(base) * "Ref"
        println(io, "struct $tname")
        println(io, "    handle::Iceoryx2FFI.iox2_$(base)_h_ref")
        println(io, "end")
        println(io)
        println(io, "@inline unsafe_handle(obj::$tname) = obj.handle")
        println(io, "@inline Base.isvalid(obj::$tname) = obj.handle != _IOX2_NULL")
        println(io)
    end

    for base in ptr_list
        tname = _camelcase(base) * "View"
        println(io, "struct $tname")
        println(io, "    ptr::Iceoryx2FFI.iox2_$(base)_ptr")
        println(io, "end")
        println(io)
        println(io, "@inline unsafe_handle(obj::$tname) = obj.ptr")
        println(io, "@inline Base.isvalid(obj::$tname) = obj.ptr != _IOX2_NULL")
        println(io)
    end

    mkpath(dirname(out_path))
    write(out_path, String(take!(io)))
    return nothing
end

function generate_errors(ffi_text::AbstractString, out_path::AbstractString)
    enums = [(String(m.captures[1]), String(m.captures[2])) for m in eachmatch(_ENUM_RE, ffi_text)]
    sort!(enums; by = x -> string(x[1], "_", x[2]))
    error_strings = _collect_error_strings(ffi_text)

    io = IOBuffer()
    println(io, "# This file is autogenerated by gen/gen-bindings.jl from src/Iceoryx2FFI.jl. Do not edit by hand.")
    println(io)
    println(io, "const _IOX2_OK = Iceoryx2FFI.IOX2_OK")
    println(io)

    for (base, kind) in enums
        enum_type = "Iceoryx2FFI.iox2_$(base)_$(kind)_e"
        println(io, "@noinline function _error_message(::Type{$enum_type}, code::$enum_type)")
        if haskey(error_strings, (base, kind))
            func = error_strings[(base, kind)]
            println(io, "    ptr = Iceoryx2FFI.$func(code)")
            println(io, "    return unsafe_string(ptr)")
        else
            println(io, "    return string(code)")
        end
        println(io, "end")
        println(io)
    end

    for (base, kind) in enums
        enum_type = "Iceoryx2FFI.iox2_$(base)_$(kind)_e"
        tname = _camelcase(base) * uppercasefirst(kind)
        println(io, "struct $tname <: Exception")
        println(io, "    code::$enum_type")
        println(io, "    message::String")
        println(io, "end")
        println(io)
        println(io, "@noinline function $tname(code::$enum_type)")
        println(io, "    return $tname(code, _error_message($enum_type, code))")
        println(io, "end")
        println(io)
        println(io, "function Base.showerror(io::IO, err::$tname)")
        println(io, "    print(io, \"$(tname): \", err.message, \" (\", err.code, \")\")")
        println(io, "end")
        println(io)
    end

    for (base, kind) in enums
        enum_type = "Iceoryx2FFI.iox2_$(base)_$(kind)_e"
        tname = _camelcase(base) * uppercasefirst(kind)
        println(io, "@inline function check_ok(code::Cint, ::Type{$enum_type})")
        println(io, "    if code == _IOX2_OK")
        println(io, "        return nothing")
        println(io, "    end")
        println(io, "    err = $enum_type(code)")
        println(io, "    throw($tname(err))")
        println(io, "end")
        println(io)
    end

    mkpath(dirname(out_path))
    write(out_path, String(take!(io)))
    return nothing
end
