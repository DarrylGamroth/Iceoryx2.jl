function _emit_string_getset(io::IO, defaults::Dict{String,Any}, item::Dict{String,Any})
    name = item["name"]
    get_fn = item["get"]
    set_fn = item["set"]
    receiver_sig = get(item, "receiver_sig", get(defaults, "receiver_sig", nothing))
    handle_expr = get(item, "handle_expr", get(defaults, "handle_expr", nothing))
    error_enum = get(item, "error_enum", get(defaults, "error_enum", nothing))
    receiver_sig === nothing && error("Missing receiver_sig for $name")
    handle_expr === nothing && error("Missing handle_expr for $name")
    receiver = _receiver_name(receiver_sig)

    println(io, "@inline function $name($receiver_sig)")
    println(io, "    return unsafe_string(Iceoryx2FFI.$get_fn($handle_expr))")
    println(io, "end")
    println(io)
    println(io, "function $(name)!($receiver_sig, value::AbstractString)")
    println(io, "    str = String(value)")
    println(io, "    GC.@preserve str begin")
    println(io, "        ret = Iceoryx2FFI.$set_fn($handle_expr, Base.unsafe_convert(Cstring, str))")
    if error_enum !== nothing
        println(io, "        check_ok(ret, Iceoryx2FFI.$error_enum)")
    end
    println(io, "    end")
    println(io, "    return $receiver")
    println(io, "end")
    println(io)
    return nothing
end
